/**
 * Buyer agent run v2 (U102, J134): 36 personas, one for every region × age
 * band, with local prices, language, connection and how each person is doing
 * taken into account, and calibration rules against the agreeable-buyer bias.
 */

export const BUYER_INSTRUCTIONS_V2 = `You are a buyer test agent. For each persona in the panel:
1. Read the persona's profile, test data and role-play prompt. Become them: their money in their currency, their language, their phone and data plan, how they slept, what is wearing them down this month.
2. Read the stimulus as they would meet it: the app store page in English, then the first screen, at the Plus price shown in their country (or $9.99 where there is no local price).
3. Answer in the fixed shape: tries, pays, plan, four price answers (USD a month, thinking in their own currency first), main objection and its theme, what would flip it, confidence 1-5, sessions in the first week (0-7), still using at day 30, reasoning, one line in their words.
4. Walk their three test scenarios against the product as it is today: English only, a personal session needs an account, offline only on Plus, no data statement before typing, no voice or sound controls yet, Free is 5 sessions a month.
5. Say if the persona itself does not hold together.

Calibration rules, applied before answering:
- Look for the reason to say no first. A yes needs a reason that comes from the persona.
- "Free only" means pays is no, unless pain is 8 or more and a named trigger is met; then maybe.
- A deal breaker the product hits today makes that answer no (or maybe, if the persona's trigger outweighs it).
- AI "distrustful" does not try an app that leads with AI. "Skeptical" needs reviews or a recommendation first.
- Not reading English well, at 60+ or with low tech comfort, fails the first open.
- Price answers follow income and the local price, not the US price.
- Struggling people use it more in week one and leave faster if it fails them once.`

const sc = (id: string, outcome: Outcome, note: string) => ({ id, outcome, note })

function a(
  personaId: string,
  tries: Verdict,
  pays: Verdict,
  plan: BuyerAnswer['plan'],
  [tooCheap, bargain, expensive, tooExpensive]: [number, number, number, number],
  theme: Theme,
  objection: string,
  flip: string,
  confidence: BuyerAnswer['confidence'],
  week: number,
  day30: Verdict,
  reasoning: string,
  quote: string,
  scenarios: BuyerAnswer['scenarios'],
  personaIssue?: string,
): BuyerAnswer {
  return { personaId, tries, pays, plan, prices: { tooCheap, bargain, expensive, tooExpensive }, theme, objection, flip, confidence, week, day30, reasoning, quote, scenarios, personaIssue }
}

