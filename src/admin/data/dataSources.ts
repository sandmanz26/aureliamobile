export interface ResolvedDataSource extends DataSourceUse {
  source: ReportSource
  type: DataSourceType
  file: string
  date: string
}

export function dataSourcesFor(route: string): ResolvedDataSource[] {
  return (REPORT_DATA_SOURCES[route]?.uses ?? []).map((u) => ({ ...u, source: SOURCES[u.id], ...SOURCE_META[u.id] }))
}
