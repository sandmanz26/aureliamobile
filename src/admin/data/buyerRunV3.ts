const sc = (id: string, outcome: Outcome, note: string) => ({ id, outcome, note })

function a(
  personaId: string,
  control: [Verdict, Verdict, string],
  tries: Verdict,
  pays: Verdict,
  plan: BuyerAnswer['plan'],
  [tooCheap, bargain, expensive, tooExpensive]: [number, number, number, number],
  theme: Theme,
  objection: string,
  flip: string,
  confidence: BuyerAnswer['confidence'],
  week: number,
  day30: Verdict,
  movedBy: V3Change[],
  reasoning: string,
  quote: string,
  scenarios: BuyerAnswer['scenarios'],
  personaIssue?: string,
): BuyerAnswer {
  return {
    personaId,
    control: { tries: control[0], pays: control[1], why: control[2] },
    tries,
    pays,
    plan,
    prices: { tooCheap, bargain, expensive, tooExpensive },
    theme,
    objection,
    flip,
    confidence,
    week,
    day30,
    movedBy,
    reasoning,
    quote,
    scenarios,
    personaIssue,
  }
}

