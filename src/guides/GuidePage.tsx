/**
 * /guide — the team's documents, readable on any site (production included)
 * behind the same site password as the app. One shell, three documents:
 * the admin guideline (generated by scripts/guides/admin_guideline.py) and
 * two Markdown files rendered as they stand in docs/, so the page can never
 * drift from the file it shows.
 */
const DOCS = [
  {
    id: 'admin',
    title: 'Admin guideline',
    blurb: 'Every admin module: purpose, what you see, what you can do, rules, permissions, and what the backend replaces.',
    icon: BookOpen,
    source: 'scripts/guides/admin_guideline.py',
    html: () => adminGuideline,
  },
  {
    id: 'playbook',
    title: 'PM playbook',
    blurb: 'The feedback group, for the project manager: the six milestones over eight weeks, the daily rhythm, iterating with the product team, and where the admin shows each step.',
    icon: MapIcon,
    source: 'scripts/guides/pm_playbook.py',
    html: () => pmPlaybook,
  },
  {
    id: 'prd',
    title: 'Product requirements',
    blurb: 'What Aurelia is, who it is for, what is built and what is not, how success is measured, and the open decisions.',
    icon: FileText,
    source: 'docs/PRD-OVERVIEW.md',
    html: () => marked.parse(prdOverview, { async: false }),
  },
  {
    id: 'api',
    title: 'API contract',
    blurb: 'The backend plan for production: conventions, data model, every endpoint, the AI system, phasing and decisions.',
    icon: Server,
    source: 'docs/api/API-CONTRACT.md',
    html: () => marked.parse(apiContract, { async: false }),
  },
] as const

type DocId = (typeof DOCS)[number]['id']

function DocTabs({ current }: { current?: DocId }) {
  return (
    <nav className="gd-tabs" aria-label="Documents">
      {DOCS.map((d) => (
        <Link key={d.id} to={`/guide/${d.id}`} aria-current={d.id === current ? 'page' : undefined}>
          {d.title}
        </Link>
      ))}
    </nav>
  )
}

function TopBar({ current }: { current?: DocId }) {
  return (
    <header className="gd-top">
      <Link to="/guide" className="gd-brand">
        <span aria-hidden="true" className="gd-mark" />
        Aurelia docs
      </Link>
      <DocTabs current={current} />
      <Link to="/admin" className="gd-back">
        <ArrowLeft size={14} aria-hidden="true" /> Admin
      </Link>
    </header>
  )
}

