// Writes the wiki's Design system tab as Markdown, from the same sources the
// page reads (design-tokens/figma-export.json and src/designsystem/*.ts).
// Run with: node --experimental-strip-types scripts/knowledge/design-system.mjs
import { readFileSync } from 'node:fs'
import { dirname, join } from 'node:path'
import { fileURLToPath } from 'node:url'

const ROOT = join(dirname(fileURLToPath(import.meta.url)), '../..')
const { parseExport, semanticUsage, gaps } = await import(join(ROOT, 'src/designsystem/tokens.ts'))
const { PATTERNS, CATALOGUE } = await import(join(ROOT, 'src/designsystem/catalogue.ts'))

const T = parseExport(readFileSync(join(ROOT, 'design-tokens/figma-export.json'), 'utf8'))
const out = []
const p = (s = '') => out.push(s)
const cell = (s) => String(s ?? '').replace(/\|/g, '\\|').replace(/\n/g, ' ')

p('# Design system')
p()
p('The pieces every Aurelia screen is made of, read from the Figma variables')
p('snapshot (`design-tokens/figma-export.json`) and the app\'s components. In the')
p('app this is the wiki\'s Design system tab (`/wiki/design-system`), which also')
p('renders the components live.')
p()
p(`${T.total} variables in ${T.collections.length} collections: ${T.collections.map((c) => `${c.name} (${c.count})`).join(', ')}.`)
p()
p('## Principles')
p()
p('- One typeface: Mulish, weights 300–600 (never 700/800; they would be faked).')
p('- Light only. Warm white surfaces, espresso text, gold for emphasis.')
p('- Every number is a pixel: spacing utilities map 1:1 (`p-16` is 16px).')
p('- A closed radius scale: 0, 2, 4, 8, 12, 16, 24, 32 and full. `rounded-[20px]` and `rounded-tl-[48px]` are deliberate raw values.')
p('- A 20px page gutter, shared with the Flutter app.')
p('- Components bind only the semantic colours; `src/styles/tokens.css` is generated, never edited.')
p()
p('## Colour')
p()
p('### Semantic (what components use)')
p()
p('| Token | Hex | Used for |')
p('| --- | --- | --- |')
for (const c of T.semantic) p(`| \`${c.name}\` | ${c.hex} | ${cell(semanticUsage(c.name) ?? '')} |`)
p()
p('### Brand ramps')
p()
for (const r of T.ramps) p(`- **${r.name}** (primitive role: ${r.alias}): ${r.steps.map(([s, h]) => `${s} ${h}`).join(', ')}`)
p()
p('### Colours with no variable yet')
p()
p('| Hex | Where | Nearest variable |')
p('| --- | --- | --- |')
for (const g of gaps) p(`| ${g.hex} | ${cell(g.where)} | ${cell(g.nearest)} |`)
p()
p('## Typography')
p()
p('| Style | Class | Size / line height | Weight |')
p('| --- | --- | --- | --- |')
for (const t of T.textStyles) p(`| ${cell(t.label)} | \`text-style-${t.name}\` | ${t.size}/${t.lineHeight} | ${t.weight} (${t.weightValue}) |`)
p()
p('## Spacing, size and radius')
p()
p(`- **Spacing:** ${T.spacing.map(([n, v]) => `${n} = ${v}`).join(', ')}`)
p(`- **Size:** ${T.size.map(([n, v]) => `${n} = ${v}`).join(', ')}`)
p(`- **Radius:** ${T.radius.map(([n, v]) => `${n} = ${v}`).join(', ')}`)
p()
p('## Components and patterns')
p()
p(`${CATALOGUE.length} components in ${PATTERNS.length} patterns. Props are read from each file in \`src/components\`.`)
for (const pat of PATTERNS) {
  p()
  p(`### ${pat.name}`)
  p()
  p(pat.guidance)
  p()
  for (const r of pat.rules) p(`- ${r}`)
  p()
  p('| Component | File | Purpose | Use when | States | Where |')
  p('| --- | --- | --- | --- | --- | --- |')
  for (const c of CATALOGUE.filter((x) => x.pattern === pat.id)) {
    p(`| ${cell(c.name)} | \`src/components/${c.file}\` | ${cell(c.purpose)} | ${cell(c.useWhen)} | ${cell(c.states.join(', '))} | ${cell(c.where)} |`)
  }
}
p()
process.stdout.write(out.join('\n'))
